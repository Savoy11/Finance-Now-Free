import Link from 'next/link'
import { LEGAL_PAGES } from '@/lib/legal'

// Footer for the app shell.
//
// BUSINESS-CHECKLIST §3 requires the disclosure documents to be linked from
// every page AND surfaced at the point of relevance — "a disclaimer nobody sees
// does not protect anyone". This is the every-page half; the point-of-relevance
// half is the provenance labelling already rendered beside the data itself.
//
// Rendered from LEGAL_PAGES so adding a document links it everywhere at once,
// and the short "not investment advice" line is stated inline rather than only
// linked, since the one-sentence version is the part most readers will ever see.
export function SiteFooter() {
  return (
    <footer className="mt-8 border-t border-border px-6 py-5">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <p className="text-[11px] text-text-muted leading-relaxed max-w-xl">
          Finance Now is an information and research tool.{' '}
          <span className="text-text-secondary">
            Nothing here is financial, investment, or legal advice
          </span>{' '}
          — including anything generated by AI. Verify figures against primary sources before
          acting on them.
        </p>
        <nav className="flex flex-wrap gap-x-3 gap-y-1 sm:justify-end shrink-0">
          {LEGAL_PAGES.map((p) => (
            <Link
              key={p.slug}
              href={`/legal/${p.slug}`}
              title={p.summary}
              className="text-[11px] text-text-muted hover:text-text-secondary transition-colors"
            >
              {p.title}
            </Link>
          ))}
        </nav>
      </div>
    </footer>
  )
}
